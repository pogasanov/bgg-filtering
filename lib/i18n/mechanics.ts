/** A mechanic's name in the interface language. */
export function mechanicLabel(name: string, locale: Locale): string {
  return locale === "ru" ? (mechanicNamesRu[name] ?? name) : name;
}

/** Folds case and ё, so a search finds "ёлка" by "елка". */
function fold(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е");
}

/** True when the query is part of the mechanic's English or Russian name, whatever the interface language. */
export function mechanicMatches(name: string, query: string): boolean {
  const needle = fold(query.trim());
  if (needle === "") return true;
  return fold(name).includes(needle) || fold(mechanicNamesRu[name] ?? "").includes(needle);
}
